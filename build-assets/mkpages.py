#!/usr/bin/env python3
"""Build step only; nothing in here runs on the target.

Assembles window.S and data.S for the addresses they have in the running program (build-assets/layout.ld), and packs the
result into the two files the driver is compiled with:
    build/pages.h    NPAGES and page_table[] = (address, kind) of every 4 KB page the driver maps
    build/pages.bin  the contents of those pages, 4096 bytes each, same order
kind 0 = code (r-x), 1 = read-only data, 2 = writable data.

usage: mkpages.py CC LD      e.g.  mkpages.py "clang --target=riscv64-linux-gnu" ld.lld"""
import os, re, struct, subprocess, sys
cc, ld = sys.argv[1].split(), sys.argv[2]
os.makedirs('build', exist_ok=True)
for f in ('window', 'data'):
    subprocess.run(cc + ['-march=rv64gc', '-mno-relax', '-c', '-o', 'build/%s.o' % f, f + '.S'], check=True)
subprocess.run([ld, '--no-relax', '-T', 'build-assets/layout.ld', '-e', '0', '-o', 'build/window.elf', 'build/window.o', 'build/data.o'], check=True)
elf = open('build/window.elf', 'rb').read(); pages = {}
def sections(e):          # (name, address, file offset, size) of every section with contents, read from the ELF64 section headers
    shoff, = struct.unpack_from('<Q', e, 0x28); shentsize, shnum, shstrndx = struct.unpack_from('<HHH', e, 0x3a)
    hdr = [struct.unpack_from('<IIQQQQ', e, shoff + i * shentsize) for i in range(shnum)]      # name, type, flags, addr, offset, size
    stroff = hdr[shstrndx][4]
    for nameoff, typ, flags, addr, off, size in hdr:
        if typ == 1: yield e[stroff + nameoff:e.index(b'\0', stroff + nameoff)].decode(), addr, off, size      # SHT_PROGBITS
for name, addr, off, size in sections(elf):
    if not re.match(r'\.(r_|g_|data2_|front)', name): continue
    kind = 0 if name.startswith(('.r_', '.front')) else 1 if name.startswith('.g_') else 2
    if kind == 2: pages.setdefault(addr & ~0xfff, [kind, bytearray(4096)])          # data pages exist even where they are zero
    for k, x in enumerate(elf[off:off + size]):
        if x: pages.setdefault((addr + k) & ~0xfff, [kind, bytearray(4096)])[1][(addr + k) & 0xfff] = x   # gaps inside a code region stay unmapped
order = [(a, k, d) for a, (k, d) in sorted(pages.items())]
h = '/* generated by build-assets/mkpages.py from window.S and data.S */\n#define NPAGES %d\n' % len(order)
h += 'static const struct { unsigned long addr; int kind; } page_table[NPAGES] = {\n' + ',\n'.join('\t{0x%xUL, %d}' % (a, k) for a, k, d in order) + '\n};\n'
open('build/pages.h', 'w').write(h); open('build/pages.bin', 'wb').write(b''.join(bytes(d) for a, k, d in order))
print('build/pages.bin: %d pages' % len(order))
